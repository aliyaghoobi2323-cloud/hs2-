#!/usr/bin/env bash
# s49: run1.sh NAME FARM VARIANT BIN [EXTRA_IR_ENV] — s46 + arms r49 (HS2_MCONN_STRIPE_RESEND=1 both sides) and r49l (same + HS2_MCONN_STRIPE_LOG=1 both sides)
set -u
NAME=$1; export FARM=$2; V=$3; B=$4; XIR=${5:-}; D=/opt/hs2lab/s49
BB=${B%p}; BB=${BB%l}; export HS2BIN=$D/hs2-$BB
L=$D/labsrc/lab
export P3_OUT=$D/res/$NAME; rm -rf $P3_OUT; mkdir -p $P3_OUT
COMMON="HS2_SHAPE_FAST=1 HS2_SHAPE_SMALL=1 HS2_L3_LANE=1 HS2_HEAVY_BACKLOG=1 HS2_L3_DUP=1 HS2_MCONN=lite HS2_FAST_LINK=1 HS2_MCONN_BATCH=1 HS2_SHAPE_BULK=1 HS2_QUIET_IDLE=1 HS2_TLS_RESUME=1 HS2_AUTH_PAD=1 HS2_COVER_NGINX=1 HS2_MCONN_DEADLINE_FIX=1 HS2_MCONN_CLOSE_HS=1 HS2_LB_AUTO2=1 HS2_MCONN_CALL=1 HS2_MCONN_CALL_AVOID=1 HS2_MCONN_STRIPE=8 HS2_LB_JUDGE_DATA=1 HS2_LB_FAST_VERDICT=1 HS2_LB_RESCUE=1 HS2_LB_RESCUE_CALLFREE=1"
IRP="HS2_SMUX_AUTOWIN=1 HS2_SMUX_AUTOWIN_REL=1 HS2_SMUX_AUTOWIN_SHARE_MB=32 HS2_STRIPE_AW_SOLO=1 HS2_STRIPE_AW_HEAVY=2 HS2_LB_FAST_RECOVER=1 HS2_LB_START_GRACE_S=20"
KHP="HS2_SMUX_AUTOWIN=1 HS2_SMUX_AUTOWIN_REL=1 HS2_SMUX_AUTOWIN_SHARE_MB=32 HS2_MCONN_STRIPE_JUMP_MS=1500 HS2_LB_FAST_RECOVER=1 HS2_LB_START_GRACE_S=20 HS2_LB_FILL_PCT=25 HS2_LB_SPARE_PER_ROUND=3 HS2_LB_REC_CONFIRM=1"
IRE="$COMMON HS2_LINK_PROBATION=1 HS2_PARTIAL_REFILL=1 HS2_PICK_LANE=on HS2_QUEUE_CTL_UP=1 $IRP $XIR"
KHE="$COMMON HS2_QUEUE_CTL=1 $KHP ${XKH:-}"
case $B in r49*) X="HS2_MCONN_STRIPE_RESEND=1"; [ "${B%l}" != "$B" ] && X="$X HS2_MCONN_STRIPE_LOG=1"; IRE="$IRE $X"; KHE="$KHE $X";; r31) KHE="$KHE HS2_LB_FLAP_PEN=1";; r31p) IRE="$XIR"; KHE="HS2_LB_FLAP_PEN=1";; esac
export KHAREJ_EXTRA="\"max_links\":150,\"min_links\":100,"
LOSS=0; HV=down; HP=8; T=45s; KA=0; HCTL=""
case $V in
  c0) ;; c1) LOSS=0.01;;
  s) HV=""; T=30s;;
  u8) HV=up; T=30s; KA=12; HCTL=direct;;
  u1) HV=up; HP=1; T=30s; HCTL=direct;;  # one upload connection, no kill (stripe speed)
esac
export HOME=/root GOPATH=/root/go PATH=$PATH:/usr/local/go/bin MODE=l3mtcp EMU=kernel RATE=1000mbit DELAY=37ms QUEUE=100ms
export T BULK=0 CALL=2mbit GAME=1 MIN_LINKS=100 MAX_LINKS=150 CROWD=3000 REVERSE=1 NOWARM=1 WORKDIR=/tmp/s49w PATHS=3 LB_MODE=auto LOSS KILL_AT=$KA
export PPROF=0 HEAVY_CTL=$HCTL
env BIN=$D/irF.sh BIN_KH=$D/khF.sh IR_ENV="$IRE" KH_ENV="$KHE" HEAVY=$HV HEAVY_P=$HP LOGDIR=$P3_OUT RUNTAG=$NAME bash $L/run.sh > $P3_OUT/run.out 2> $P3_OUT/run.err
tail -1 $P3_OUT/run.out > $P3_OUT/result.json
echo "LAB_ID=${LAB_ID:-} FARM=$FARM V=$V B=$B XIR=$XIR" > $P3_OUT/meta.txt
