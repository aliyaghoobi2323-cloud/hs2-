#!/bin/bash
# seq116.sh JOBFILE: "TAG ARM MODE" lines one by one on the whole lab (seq60 design, 1 retry on iperf3 error).
D=/opt/hs2lab/dr116; mkdir -p $D/res
while read -r t a m x; do [ -z "$t" ] && continue; [ -e $D/stop ] && break
  for try in 1 2; do
    /opt/hs2lab/labslot.sh --all $D/d116.sh $t $a $m
    grep -q '"error"' $D/res/$t/heavy.json 2>/dev/null || break
    echo "$(date +%T) $t retry" >> $D/res/seq.log; sleep 5
  done
  echo "$(date +%T) $t" >> $D/res/seq.log
done < $1
echo ALLDONE > $D/res/ALLDONE.$(basename $1)
